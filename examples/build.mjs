#!/usr/bin/env node
// Runs every case in cases.json through snap.mjs, checks each result against its `expect`,
// and writes examples/README.md (+ refs/*.png).
//
//   node examples/build.mjs            run all cases, write README + screenshots
//   node examples/build.mjs --check    run and verify only (smoke test; nothing written to examples/)
//   node examples/build.mjs --offline  skip cases that need live websites
//   node examples/build.mjs --only exact,duplicate-prefix
// Exit code 1 if any case fails its expectations.

import { createServer } from 'node:http';
import { readFileSync, existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { execFile } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, dirname, extname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const HERE = dirname(fileURLToPath(import.meta.url));
const SNAP = join(HERE, '..', 'skills', 'citing-sources-with-excerpts', 'scripts', 'snap.mjs');
// Playwright lives with the skill's script, not in examples/.
const { chromium } = createRequire(join(dirname(SNAP), 'package.json'))('playwright');
const FIXTURES = join(HERE, 'fixtures');
const PORT = 4317; // fixed, so links in the README are stable
const BASE = `http://127.0.0.1:${PORT}`;

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const offline = argv.includes('--offline');
const onlyArg = argv.find((a) => a.startsWith('--only'));
const only = onlyArg ? (onlyArg.includes('=') ? onlyArg.split('=')[1] : argv[argv.indexOf(onlyArg) + 1]).split(',') : null;

// ---------- fixture server ----------

const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.json': 'application/json', '.pdf': 'application/pdf' };
const server = createServer((req, res) => {
  const url = new URL(req.url, BASE);
  if (url.pathname === '/redirect') { res.writeHead(302, { Location: '/article.html' }); return res.end(); }
  if (url.pathname === '/redirect-metadata') { res.writeHead(302, { Location: 'http://169.254.169.254/latest/meta-data/' }); return res.end(); }
  if (url.pathname === '/data.json') {
    const delay = Math.min(5000, Number(url.searchParams.get('delay')) || 0);
    return setTimeout(() => {
      res.writeHead(200, { 'Content-Type': TYPES['.json'] });
      res.end(JSON.stringify({ text: 'All systems are operating normally.' }));
    }, delay);
  }
  const file = join(FIXTURES, url.pathname.replace(/^\/+/, ''));
  if (!file.startsWith(FIXTURES) || !existsSync(file) || url.pathname === '/') { res.writeHead(404, { 'Content-Type': TYPES['.html'] }); return res.end('<h1>Not found</h1>'); }
  res.writeHead(200, { 'Content-Type': TYPES[extname(file)] || 'application/octet-stream' });
  res.end(readFileSync(file));
});

// ---------- checks ----------

function verify(result, expect) {
  const fails = [];
  const has = (field, sub) => typeof result[field] === 'string' && result[field].includes(sub);
  for (const [k, v] of Object.entries(expect)) {
    if (k === 'link') continue; // checked in the browser, below
    if (k === 'error' || k === 'note' || k === 'fragment') {
      const field = k === 'fragment' ? 'fragment_url' : k;
      if (!has(field, v)) fails.push(`${field} should contain ${JSON.stringify(v)} (got ${JSON.stringify(result[field] ?? null)})`);
    } else if (k === 'screenshot') {
      if (Boolean(result.screenshot) !== v) fails.push(v ? 'expected a screenshot' : 'expected no screenshot');
      else if (v) {
        // PNG header: width and height are big-endian at bytes 16-23. Reject slivers (2x scale -> px/2).
        const png = readFileSync(result.screenshot);
        const w = png.readUInt32BE(16), h = png.readUInt32BE(20);
        if (w < 80 || h < 24) fails.push(`screenshot is a ${w}x${h} sliver, not a usable crop`);
      }
    } else if ((result[k] ?? (k === 'hidden' || k === 'internal' ? false : null)) !== v) {
      fails.push(`${k} should be ${JSON.stringify(v)} (got ${JSON.stringify(result[k] ?? null)})`);
    }
  }
  return fails;
}

// ---------- README ----------

const code = (lang, s) => `\`\`\`${lang}\n${s}\n\`\`\``;
function footnote(c, r) {
  const label = r.section ? `${r.title} — ${r.section}` : r.title;
  const lines = [`[^${c.id}]: > ${r.quote_on_page}`, '    >', `    > — [${label}](${r.fragment_url}) · retrieved ${r.retrieved}`];
  if (r.screenshot) lines.push('    >', `    > ![${c.title}](refs/${c.id}.png)`);
  return lines.join('\n');
}
function shownInput(c) {
  const o = { ...c.cite };
  if (o.out) o.out = `refs/${c.id}.png`;
  return JSON.stringify(o, null, 2).replaceAll('{{base}}', BASE);
}

function readme(data, rows) {
  const out = [
    '# Examples and edge cases',
    '',
    'Every case below is generated by [`build.mjs`](build.mjs) from [`cases.json`](cases.json): it runs the input through `snap.mjs`, checks the result against what the case expects, and opens every generated link in Chromium to confirm it really jumps to the quote.',
    '',
    'Cases marked 🌐 use live websites; the rest use small local pages in [`fixtures/`](fixtures), served from `http://127.0.0.1:4317` (so their links only work while `build.mjs` is running).',
    '',
    '```bash',
    'node examples/build.mjs            # regenerate this page',
    'node examples/build.mjs --check    # smoke test: verify only, write nothing',
    'node examples/build.mjs --offline  # skip the 🌐 cases',
    '```',
    '',
    `Last run: ${new Date().toISOString().slice(0, 10)} · ${rows.filter((r) => !r.fails.length).length}/${rows.length} cases pass.`,
    '',
  ];
  for (const g of data.groups) {
    const gr = rows.filter((r) => r.c.group === g.id);
    if (!gr.length) continue;
    out.push(`## ${g.title}`, '');
    const screenshotsGroup = g.id === 'screenshots';
    out.push(screenshotsGroup ? '| Case | Prompt wording | Pass |\n|---|---|---|' : '| Case | Result | Pass |\n|---|---|---|');
    for (const { c, r, fails } of gr) {
      const what = screenshotsGroup ? (c.prompt || '') : r.ok ? `\`${r.match}\`${r.hidden ? ', hidden' : ''}${r.occurrences ? `, occurrence ${r.occurrence} of ${r.occurrences}` : ''}` : r.error ? 'error' : '`none`';
      out.push(`| [${c.live ? '🌐 ' : ''}${c.title}](#${c.id}) | ${what} | ${fails.length ? '❌' : '✅'} |`);
    }
    out.push('');
    for (const { c, r, fails } of gr) {
      out.push(`<a id="${c.id}"></a>`, `### ${c.live ? '🌐 ' : ''}${c.title}`, '', c.why, '');
      if (c.prompt) out.push(`Prompt wording: ${c.prompt}`, '');
      if (fails.length) out.push(`> [!WARNING]\n> Failed: ${fails.join('; ')}`, '');
      out.push('<details><summary>Input</summary>', '', code('json', shownInput(c)), '', '</details>', '');
      if (r.ok) {
        const bits = [`**match:** \`${r.match}\``];
        if (r.internal) bits.push('**internal:** true');
        if (r.occurrences) bits.push(`**occurrence:** ${r.occurrence} of ${r.occurrences}`);
        if (r.hidden) bits.push('**hidden:** true');
        if (r.link === true) bits.push('**link:** highlights the quote in Chromium');
        if (r.link === false) bits.push('**link:** does not highlight in browsers (expected)');
        out.push(bits.join(' · '), '');
        if (r.note) out.push(`**note:** ${r.note.replaceAll(BASE, 'http://127.0.0.1:4317')}`, '');
        out.push('What the skill writes:', '', code('md', footnote(c, r).replaceAll(BASE, 'http://127.0.0.1:4317')), '');
        if (r.screenshot) out.push(`<img src="refs/${c.id}.png" alt="${c.title}" width="${Math.min(720, c.cite.width || 720)}">`, '');
      } else {
        out.push(r.error ? `**error:** ${r.error}` : '**match:** `none`, not on the page', '');
      }
    }
  }
  return out.join('\n') + '\n';
}

// ---------- main ----------

const data = JSON.parse(readFileSync(join(HERE, 'cases.json'), 'utf8'));
const cases = data.cases.filter((c) => (!offline || !c.live) && (!only || only.includes(c.id)));
const refsDir = check ? mkdtempSync(join(tmpdir(), 'receipts-check-')) : join(HERE, 'refs');
mkdirSync(refsDir, { recursive: true });

await new Promise((ok) => server.listen(PORT, '127.0.0.1', ok));
const batch = cases.map((c) => {
  const cite = JSON.parse(JSON.stringify(c.cite).replaceAll('{{base}}', BASE));
  if (cite.out) cite.out = join(refsDir, `${c.id}.png`);
  return cite;
});
const t0 = Date.now();
const stdout = await new Promise((ok, fail) => {
  const p = execFile(process.execPath, [SNAP, '--batch', '-', '--timeout', '15000'], { maxBuffer: 64 << 20 }, (err, out) => {
    if (out) ok(out); else fail(err);
  });
  p.stdin.end(JSON.stringify(batch));
});
const results = JSON.parse(stdout);

// ---------- browser link check ----------
// Does each fragment_url actually make a browser jump to the quote? A 4000px spacer is inserted at
// the top of the page before the browser processes the fragment, so any match must scroll past it,
// even for quotes at the very top. A nonsense fragment runs first to prove "no match" reads as 0.
const SPACER = 4000;
async function linkMatches(browser, url) {
  const page = await browser.newPage({ viewport: { width: 1100, height: 600 } });
  try {
    await page.addInitScript((h) => {
      document.addEventListener('DOMContentLoaded', () => {
        const d = document.createElement('div');
        d.style.height = h + 'px';
        document.body.prepend(d);
      });
    }, SPACER);
    await page.goto(url, { waitUntil: 'load', timeout: 20000 }).catch(() => {});
    // Fragment scrolling can lag the load event; poll briefly.
    for (let i = 0; i < 10; i++) {
      if ((await page.evaluate(() => scrollY)) >= SPACER - 1000) return true;
      await page.waitForTimeout(200);
    }
    return false;
  } finally {
    await page.close();
  }
}
// Cases may set expect.link to false: the link is known not to highlight (e.g. text added after load).
const toCheck = cases.map((c, i) => [c, results[i]]).filter(([c, r]) => r?.ok && r.fragment_url && !r.hidden);
const linkResults = new Map();
{
  const browser = await chromium.launch();
  try {
    if (await linkMatches(browser, `${BASE}/article.html#:~:text=zzqx%20not%20on%20this%20page`)) throw new Error('link check is broken: a nonsense fragment counted as a match');
    if (!(await linkMatches(browser, `${BASE}/article.html#:~:text=Every%20API%20key%20has%20a%20request%20budget`))) throw new Error('link check is broken: a known-good fragment did not match');
    const queue = [...toCheck];
    const worker = async () => { for (let item; (item = queue.shift()); ) linkResults.set(item[0].id, await linkMatches(browser, item[1].fragment_url)); };
    await Promise.all(Array.from({ length: 4 }, worker));
  } finally {
    await browser.close();
  }
}
server.close();
const rows = cases.map((c, i) => {
  const fails = verify(results[i], c.expect);
  const link = linkResults.get(c.id);
  const shown = results[i]?.fragment_url?.replaceAll(BASE, 'http://127.0.0.1:4317');
  if (c.expect.link === false) { if (link === true) fails.push(`expected the link not to highlight, but it did: ${shown}`); }
  else if (link === false) fails.push(`fragment_url doesn't highlight the quote in Chromium: ${shown}`);
  return { c, r: { ...results[i], link }, fails };
});

console.log(`links checked in Chromium: ${[...linkResults.values()].filter(Boolean).length}/${linkResults.size} highlight their quote`);
for (const { c, fails } of rows) console.log(`${fails.length ? '✗' : '✓'} ${c.id}${fails.length ? `\n    ${fails.join('\n    ')}` : ''}`);
const failed = rows.filter((r) => r.fails.length).length;
console.log(`\n${rows.length - failed}/${rows.length} passed in ${((Date.now() - t0) / 1000).toFixed(1)}s`);

if (check) rmSync(refsDir, { recursive: true, force: true });
else if (only || offline) console.log('(partial run: README not written; run without --only/--offline to regenerate it)');
else {
  writeFileSync(join(HERE, 'README.md'), readme(data, rows));
  console.log(`wrote ${relative(process.cwd(), join(HERE, 'README.md'))}`);
}
process.exit(failed ? 1 : 0);
